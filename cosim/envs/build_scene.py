"""Generate the co-sim MJCF files from the MuJoCo Menagerie Panda.

Writes two files next to this script:

    panda_torque.xml     Menagerie Panda with joint torque motors (instead of the stock
                         position servos), a TCP site and a wrist camera frame.
    conveyor_scene.xml   floor, robot pedestal, conveyor with animated slats, a pool of
                         mixed objects, a place bin, an overhead camera frame and a human proxy.

The generated XML is committed; rerun this script only when the layout changes:

    .venv/bin/python cosim/envs/build_scene.py
"""

from __future__ import annotations

import os
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
MENAGERIE_PANDA = ROOT / "third_party/mujoco_menagerie/franka_emika_panda"

# Layout (world frame, metres). Robot base at the origin, floor at z = 0.
# These numbers are shared with the web viewer through cosim/export_scene.py.
CONVEYOR = {"x": 0.56, "width": 0.34, "top_z": 0.16, "y0": -0.95, "y1": 0.95}
BIN = {"x": 0.08, "y": -0.56, "half": (0.13, 0.11), "wall_h": 0.06}
N_OBJECTS = 14
N_SLATS = 24
SLAT_PITCH = (CONVEYOR["y1"] - CONVEYOR["y0"]) / N_SLATS

# Object pool: (type, size, mass kg, rgba). Sizes are MuJoCo half sizes.
# Widths across the gripper closing axis stay under 6 cm (Panda opening is 8 cm).
OBJECT_KINDS = [
    ("box", (0.022, 0.022, 0.022), 0.10, (0.93, 0.36, 0.30, 1)),
    ("cylinder", (0.021, 0.030, 0), 0.09, (0.98, 0.76, 0.27, 1)),
    ("sphere", (0.024, 0, 0), 0.08, (0.55, 0.85, 0.52, 1)),
    ("box", (0.026, 0.018, 0.020), 0.09, (0.36, 0.72, 0.95, 1)),
    ("cylinder", (0.018, 0.024, 0), 0.06, (0.78, 0.52, 0.93, 1)),
    ("box", (0.018, 0.026, 0.025), 0.10, (0.96, 0.58, 0.20, 1)),
    ("sphere", (0.021, 0, 0), 0.06, (0.30, 0.80, 0.78, 1)),
]


def object_kind(i: int) -> tuple[str, tuple[float, float, float], float, tuple[float, ...]]:
    """Kind of pool slot i (deterministic)."""
    return OBJECT_KINDS[i % len(OBJECT_KINDS)]


def object_half_height(kind: str, size: tuple[float, float, float]) -> float:
    """Half height of an upright object (box z half size, cylinder half length, sphere radius)."""
    if kind == "box":
        return size[2]
    if kind == "cylinder":
        return size[1]
    return size[0]


def parked_pos(i: int) -> tuple[float, float, float]:
    """Where an unused pool object waits (on the floor, behind the robot, out of view)."""
    _, size, _, _ = object_kind(i)
    return (-1.6, -0.9 + 0.13 * i, object_half_height(object_kind(i)[0], size) + 0.001)


def _fmt(v) -> str:
    return " ".join(f"{x:.6g}" for x in v)


def build_panda_torque() -> str:
    src = (MENAGERIE_PANDA / "panda.xml").read_text()
    meshdir = os.path.relpath(MENAGERIE_PANDA / "assets", HERE)
    src = src.replace('meshdir="assets"', f'meshdir="{meshdir}"')
    src = src.replace('<mujoco model="panda">', '<mujoco model="panda_torque">')
    # TCP site (fingertip pad centre) and wrist camera frame on the hand.
    hand_open = re.search(r'<body name="hand"[^>]*>', src)
    assert hand_open
    extra = (
        '\n                      <site name="tcp" pos="0 0 0.1034" size="0.006" rgba="1 0.2 0.2 1" group="4"/>'
        '\n                      <camera name="cam_wrist" pos="0.05 0 0.06" quat="0 1 0 0" fovy="75"/>'
    )
    src = src[: hand_open.end()] + extra + src[hand_open.end():]
    # Replace the seven position servos with torque motors (limits from the Panda datasheet).
    act = re.search(r"<actuator>.*?</actuator>", src, flags=re.S)
    assert act
    lim = [87, 87, 87, 87, 12, 12, 12]
    motors = "\n".join(
        f'    <motor name="actuator{i + 1}" joint="joint{i + 1}" ctrlrange="{-l} {l}" forcerange="{-l} {l}"/>'
        for i, l in enumerate(lim)
    )
    grip = re.search(r'<general class="panda" name="actuator8".*?/>', act.group(0), flags=re.S)
    assert grip
    new_act = "<actuator>\n" + motors + "\n    " + grip.group(0) + "\n  </actuator>"
    src = src[: act.start()] + new_act + src[act.end():]
    # Keyframes would not match the larger scene qpos; the co-sim sets the home pose in code.
    src = re.sub(r"<keyframe>.*?</keyframe>", "", src, flags=re.S)
    header = "<!-- Generated by cosim/envs/build_scene.py from MuJoCo Menagerie franka_emika_panda/panda.xml. -->\n"
    return header + src


def build_scene() -> str:
    c = CONVEYOR
    length = c["y1"] - c["y0"]
    cy = (c["y0"] + c["y1"]) / 2
    top = c["top_z"]
    out: list[str] = []
    w = out.append
    w("<!-- Generated by cosim/envs/build_scene.py. Conveyor pick scene for the Glass Chip co-sim. -->")
    w('<mujoco model="glasschip_conveyor">')
    w('  <include file="panda_torque.xml"/>')
    w('  <option timestep="0.001" integrator="implicitfast" cone="elliptic" impratio="5"/>')
    w('  <size memory="64M"/>')
    w("  <visual>")
    w('    <headlight diffuse="0.6 0.6 0.6" ambient="0.3 0.3 0.3" specular="0 0 0"/>')
    w('    <global azimuth="140" elevation="-25" offwidth="1280" offheight="720"/>')
    w("  </visual>")
    w("  <asset>")
    w('    <texture type="2d" name="floortex" builtin="checker" mark="edge" rgb1="0.82 0.83 0.85" '
      'rgb2="0.76 0.77 0.79" markrgb="0.7 0.7 0.7" width="300" height="300"/>')
    w('    <material name="floor" texture="floortex" texuniform="true" texrepeat="4 4" reflectance="0.05"/>')
    w("  </asset>")
    w("  <worldbody>")
    w('    <light pos="0.3 0 2.5" dir="0 0 -1" directional="true"/>')
    w('    <geom name="floor" type="plane" size="3 3 0.05" material="floor"/>')
    w('    <geom name="pedestal" type="cylinder" size="0.11 0.002" pos="0 0 0.002" rgba="0.3 0.31 0.33 1" '
      'contype="0" conaffinity="0"/>')
    # Conveyor: the belt geom has priority so its (near zero) friction governs object contacts;
    # the belt drive itself is a friction-limited force applied in cosim/conveyor.py.
    w(f'    <geom name="belt" type="box" size="{c["width"] / 2} {length / 2} 0.012" '
      f'pos="{c["x"]} {cy} {top - 0.012}" rgba="0.16 0.17 0.19 1" priority="1" friction="0.02 0.005 0.0001"/>')
    w(f'    <geom name="conveyor_frame" type="box" size="{c["width"] / 2 + 0.02} {length / 2 + 0.01} 0.05" '
      f'pos="{c["x"]} {cy} {top - 0.075}" rgba="0.55 0.58 0.62 1"/>')
    for sx in (-1, 1):
        w(f'    <geom name="rail_{"l" if sx < 0 else "r"}" type="box" size="0.008 {length / 2 + 0.01} 0.018" '
          f'pos="{c["x"] + sx * (c["width"] / 2 + 0.012)} {cy} {top + 0.004}" rgba="0.78 0.80 0.83 1" '
          f'contype="0" conaffinity="0"/>')
    leg_h = (top - 0.125) / 2
    for j, yy in enumerate((c["y0"] + 0.08, c["y1"] - 0.08)):
        for sx in (-1, 1):
            w(f'    <geom name="leg_{j}_{"l" if sx < 0 else "r"}" type="box" size="0.02 0.02 {leg_h:.4f}" '
              f'pos="{c["x"] + sx * (c["width"] / 2 - 0.01)} {yy} {leg_h:.4f}" rgba="0.42 0.45 0.49 1"/>')
    # Place bin.
    b = BIN
    hx, hy = b["half"]
    t = 0.006
    hz = b["wall_h"]
    for name, dx, dy, sx_, sy_ in (("bin_xp", hx, 0, t, hy), ("bin_xn", -hx, 0, t, hy),
                                   ("bin_yp", 0, hy, hx, t), ("bin_yn", 0, -hy, hx, t)):
        w(f'    <geom name="{name}" type="box" size="{sx_} {sy_} {hz}" pos="{b["x"] + dx} {b["y"] + dy} {hz}" '
          f'rgba="0.24 0.47 0.85 1" friction="1 0.01 0.001"/>')
    w(f'    <geom name="bin_floor" type="box" size="{hx} {hy} {t}" pos="{b["x"]} {b["y"]} {t}" '
      f'rgba="0.20 0.38 0.70 1" friction="1.2 0.02 0.001"/>')
    # Overhead camera frame (geometry and visibility only; nothing renders it).
    w('    <camera name="cam_overhead" pos="0.56 -0.30 1.30" xyaxes="1 0 0 0 1 0" fovy="70"/>')
    w('    <site name="overhead_mount" pos="0.56 -0.30 1.32" size="0.03" rgba="0.2 0.2 0.2 1" group="4"/>')
    # Belt slats: kinematic visual markers that make belt motion visible in replays.
    for k in range(N_SLATS):
        y = c["y0"] + (k + 0.5) * SLAT_PITCH
        w(f'    <body name="slat_{k}" mocap="true" pos="{c["x"]} {y:.4f} {top + 0.0006}">')
        w(f'      <geom type="box" size="{c["width"] / 2 - 0.004} 0.004 0.0006" rgba="0.26 0.27 0.30 1" '
          f'contype="0" conaffinity="0" group="1"/>')
        w("    </body>")
    # Object pool.
    for i in range(N_OBJECTS):
        kind, size, mass, rgba = object_kind(i)
        p = parked_pos(i)
        w(f'    <body name="obj_{i}" pos="{_fmt(p)}">')
        w(f'      <freejoint name="obj_{i}_free"/>')
        sz = _fmt(size[:3] if kind == "box" else size[:2] if kind == "cylinder" else size[:1])
        w(f'      <geom name="obj_{i}_geom" type="{kind}" size="{sz}" mass="{mass}" rgba="{_fmt(rgba)}" '
          f'condim="4" friction="1.0 0.02 0.002" solref="0.004 1" solimp="0.95 0.99 0.001"/>')
        w("    </body>")
    # Human proxy: kinematic capsule plus head, no collisions (distance is computed analytically).
    w('    <body name="human" mocap="true" pos="2.2 0.0 0">')
    w('      <geom name="human_torso" type="capsule" fromto="0 0 0.2 0 0 1.45" size="0.18" '
      'rgba="0.85 0.88 0.92 0.6" contype="0" conaffinity="0" group="1"/>')
    w('      <geom name="human_head" type="sphere" pos="0 0 1.66" size="0.11" '
      'rgba="0.85 0.88 0.92 0.6" contype="0" conaffinity="0" group="1"/>')
    w("    </body>")
    w("  </worldbody>")
    w("</mujoco>")
    return "\n".join(out) + "\n"


def main() -> None:
    (HERE / "panda_torque.xml").write_text(build_panda_torque())
    (HERE / "conveyor_scene.xml").write_text(build_scene())
    print("wrote", HERE / "panda_torque.xml", HERE / "conveyor_scene.xml")


if __name__ == "__main__":
    main()
