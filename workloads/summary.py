"""Print a per-task table of the generated task graphs and save it to workloads/graphs/SUMMARY.md.

Columns: method, ops, layers, GMAC, GFLOP, weight MB, activation MB (bytes_in + bytes_out),
arithmetic intensity (FLOP per byte over weights + activations), CPU/RT instructions, period, deadline.

Run: .venv/bin/python workloads/summary.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GRAPHS = ROOT / "workloads" / "graphs"


def rows() -> list[dict]:
    out = []
    for p in sorted(GRAPHS.glob("T*.json"), key=lambda q: (int(q.stem.split("_")[0][1:]), q.stem)):
        g = json.loads(p.read_text())
        ops = g["ops"]
        macs = sum(o.get("macs", 0) for o in ops)
        flops = sum(o.get("flops", 0) for o in ops)
        w = sum(o.get("bytes_w", 0) for o in ops)
        act = sum(o.get("bytes_in", 0) + o.get("bytes_out", 0) for o in ops)
        instr = sum(sum(o.get("instr", {}).values()) for o in ops)
        out.append({"task": g["task_id"], "method": g["provenance"]["method"], "ops": len(ops),
                    "layers": len({o.get("layer", o["op_id"]) for o in ops}),
                    "gmac": macs / 1e9, "gflop": flops / 1e9, "w_mb": w / 1e6, "act_mb": act / 1e6,
                    "ai": flops / (w + act) if (w + act) else 0.0, "instr": instr,
                    "period_ms": g["release"].get("period_us", 0) / 1e3, "deadline_ms": g["deadline_us"] / 1e3,
                    "kind": g["release"]["kind"], "crit": g["criticality"]})
    return out


def table(rs: list[dict]) -> str:
    head = ("| Task | Method | Ops | Layers | GMAC | GFLOP | Weight MB | Activation MB | FLOP/B | CPU/RT instr | "
            "Release | Period ms | Deadline ms | Criticality |")
    sep = "|" + "---|" * 14
    lines = [head, sep]
    for r in rs:
        lines.append(f"| {r['task']} | {r['method']} | {r['ops']} | {r['layers']} | {r['gmac']:.3f} | {r['gflop']:.3f} | "
                     f"{r['w_mb']:.2f} | {r['act_mb']:.2f} | {r['ai']:.1f} | {r['instr']:,} | {r['kind']} | "
                     f"{r['period_ms']:.1f} | {r['deadline_ms']:.1f} | {r['crit']} |")
    return "\n".join(lines)


def main() -> None:
    rs = rows()
    t = table(rs)
    mw = json.loads((GRAPHS / "middleware.json").read_text())
    c, z, e = mw["copy"], mw["zero_copy"], mw["executor"]
    md = ("# Task graph summary\n\n"
          "Generated by `workloads/summary.py` from `workloads/graphs/*.json`. Weight and activation bytes assume the "
          "deployment dtypes recorded per op (int8 for most NPU work). Activation MB is the sum of every op's input "
          "and output bytes, so it counts traffic, not peak memory. Periods and deadlines are the spec defaults, not "
          "measured requirements.\n\n" + t + "\n\n"
          "## Middleware (T9, per message)\n\n"
          f"Copy transport: serialize {c['serialize_ns_per_kb']} ns/KB, deserialize {c['deserialize_ns_per_kb']} ns/KB, "
          f"fixed {c['fixed_ns_per_msg']} ns per message, {c['copies']} extra copies at {c['copy_ns_per_kb']} ns/KB. "
          f"Zero copy: fixed {z['fixed_ns_per_msg']} ns per message. Executor dispatch per hop: single-threaded "
          f"{e['single_threaded_dispatch_ns']} ns, multi-threaded {e['multi_threaded_dispatch_ns']} ns, events "
          f"{e['events_dispatch_ns']} ns. All target-scaled; see middleware.json for the method and the scaling assumption.\n")
    (GRAPHS / "SUMMARY.md").write_text(md)
    print(t)


if __name__ == "__main__":
    main()
