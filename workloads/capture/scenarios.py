"""Write scenario configs S1..S8 to configs/scenarios/ (format per notes/CONTRACTS.md, spec Section 6.4).

Task periods and deadlines come from each graph's release block (spec Section 6.1
defaults). They are reasonable defaults for a pick-from-conveyor task, not
measured requirements; scenarios override them only where the scenario says so.

Run: .venv/bin/python workloads/capture/scenarios.py
"""
from __future__ import annotations

from pathlib import Path
from typing import Any

import yaml

from common import GRAPHS, ROOT

OUT = ROOT / "configs" / "scenarios"
HEADER = ("# Generated by workloads/capture/scenarios.py. Do not edit by hand; edit the script and re-run.\n"
          "# Periods and deadlines come from workloads/graphs/<task>.json (spec Section 6.1). They are reasonable\n"
          "# defaults for a pick-from-conveyor task, NOT measured requirements.\n")

BASE = ["T1_ingest_wrist", "T1_ingest_overhead", "T2_detect", "T3_esdf", "T4_vla", "T5_plan", "T6_estimate",
        "T7_control", "T8_safety", "T10_record"]
T5_TRIGGER = {"sporadic_rate_hz": 2.0}   # one new grasp goal about every 0.5 s (assumption)


def task(graph: str, at: float = 0.0, **overrides: Any) -> dict[str, Any]:
    if not (GRAPHS / f"{graph}.json").exists():
        raise SystemExit(f"missing graph {graph}; run the capture scripts first")
    t: dict[str, Any] = {"graph": graph, "enabled_at_s": at}
    if graph == "T5_plan":
        overrides = {**T5_TRIGGER, **overrides}
    if overrides:
        t["overrides"] = overrides
    return t


def base_tasks() -> list[dict[str, Any]]:
    return [task(g) for g in BASE]


def scenario(name: str, desc: str, duration: float, tasks: list, events: list, robot: dict | None = None,
             ambient: float = 25, transport: str = "copy", executor: str = "single_threaded", seed: int = 1) -> dict:
    return {"name": name, "description": desc, "duration_s": duration, "seed": seed, "graph_dir": "workloads/graphs",
            "tasks": tasks, "events": events,
            "robot": robot or {"conveyor_speed_mps": 0.2, "object_spacing_m": 0.25, "human": False},
            "ambient_c": ambient, "transport": transport, "executor": executor}


def all_scenarios() -> dict[str, dict]:
    s: dict[str, dict] = {}
    s["S1_nominal"] = scenario(
        "S1 Nominal pick", "Baseline rates; detection on the wrist camera only; default 200 Mbit/s logging.", 10.0,
        base_tasks(), [])
    s["S2_second_camera"] = scenario(
        "S2 Second camera", "The overhead camera starts feeding detection mid-run (second T2 instance).", 10.0,
        base_tasks() + [task("T2_detect_overhead", 4.0)],
        [{"t_s": 4.0, "action": "enable_task", "args": {"task": "T2_detect_overhead"}}])
    s["S3_human_enters"] = scenario(
        "S3 Human enters", "A person walks into the workspace: safety escalates, replan burst, speed scaling.", 10.0,
        base_tasks(),
        [{"t_s": 3.0, "action": "human_enter",
          "args": {"from": "left", "speed_mps": 1.6, "closest_approach_m": 0.45,
                   "replan_burst": {"task": "T5_plan", "count": 4, "window_ms": 200},
                   "safety_escalation": {"task": "T8_safety", "period_us": 5000, "deadline_us": 5000},
                   "speed_scale_floor": 0.3}},
         {"t_s": 7.0, "action": "human_enter", "args": {"leave": True}}],
        robot={"conveyor_speed_mps": 0.2, "object_spacing_m": 0.25, "human": True})
    s["S4_conveyor_ramp"] = scenario(
        "S4 Conveyor ramp", "Object speed ramps 0.1 to 0.4 m/s; the latency tolerance shrinks.", 20.0, base_tasks(),
        [{"t_s": t, "action": "set_conveyor_speed", "args": {"speed_mps": v}}
         for t, v in ((0.0, 0.1), (5.0, 0.2), (10.0, 0.3), (15.0, 0.4))],
        robot={"conveyor_speed_mps": 0.1, "object_spacing_m": 0.25, "human": False})
    s["S5_hot_day"] = scenario(
        "S5 Hot day", "Ambient rises from 25 C to 50 C; thermal throttling engages.", 60.0, base_tasks(),
        [{"t_s": float(t), "action": "set_ambient", "args": {"ambient_c": 25 + 5 * (t // 10)}} for t in range(0, 60, 10)],
        ambient=25)
    extras = [("T2_detect_overhead", 2.0), ("T11_speech", 3.0), ("T12_arm2_control", 4.0), ("T13_map_save", 5.0),
              ("T14_ota", 6.0), ("T15_diag", 7.0)]
    s["S6_fifteen_at_once"] = scenario(
        "S6 Fifteen at once", ("Adds speech commands, a second arm's control loop, map saving, OTA download and "
                               "diagnostics (plus overhead detection) on top of the full stack: 16 task graphs."), 15.0,
        base_tasks() + [task(g, t) for g, t in extras],
        [{"t_s": t, "action": "enable_task", "args": {"task": g}} for g, t in extras])
    rates = [(2.0, 0.2e9), (4.0, 1e9), (6.0, 5.97e9), (8.0, 11.9e9), (10.0, 24e9), (12.0, 48e9), (14.0, 96e9)]
    s["S7_bandwidth_hog"] = scenario(
        "S7 Bandwidth hog", ("Recording bitrate steps from 0.2 to 96 Gbit/s (raw 4K30 is 5.97 Gbit/s; higher steps "
                             "stand for several raw 4K streams); DRAM traffic is about 3x the bitrate."), 16.0,
        [t for t in base_tasks() if t["graph"] != "T10_record"] + [task("T10_record_4k")],
        [{"t_s": t, "action": "set_bitrate", "args": {"task": "T10_record_4k", "bitrate_bps": b}} for t, b in rates])
    steps = [0.75, 0.70, 0.65, 0.60, 0.55, 0.50, 0.45]
    ev = []
    for i, v in enumerate(steps):
        for dom in ("npu", "cpu_a", "cpu_b"):
            vv = max(v, 0.50) if dom.startswith("cpu") else v
            ev.append({"t_s": 2.0 + 3.0 * i, "action": "set_vmin", "args": {"domain": dom, "v_min": vv}})
    s["S8_low_voltage_sweep"] = scenario(
        "S8 Low-voltage sweep", "NPU and CPU domain voltages step from nominal 0.75 V to their minimums.", 24.0,
        base_tasks(), ev)
    return s


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for key, sc in all_scenarios().items():
        p = OUT / f"{key}.yaml"
        p.write_text(HEADER + yaml.safe_dump(sc, sort_keys=False, default_flow_style=None, width=110))
        print(f"{p.relative_to(ROOT)}: {len(sc['tasks'])} tasks, {len(sc['events'])} events")


if __name__ == "__main__":
    main()
