"""Write riscv/kernels/franka_spheres.h from cuRobo's franka.yml.

Uses the real cuRobo collision spheres (center in link frame, radius) and the
self-collision ignore list, so the kernels run on the same 61 spheres and the same
694 checked pairs as workloads/capture/curobo.py. Run from the repo root:
    .venv/bin/python riscv/tools/gen_spheres.py
"""
from __future__ import annotations

from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "data/workloads/src/curobo/curobo_content_configs_robot_franka.yml"
OUT = ROOT / "riscv/kernels/franka_spheres.h"
# Link order used by the FK kernels: frames 0..7 are panda_link0..panda_link7,
# 8 is panda_hand, 9 and 10 are the fingers.
LINKS = ["panda_link0", "panda_link1", "panda_link2", "panda_link3", "panda_link4", "panda_link5",
         "panda_link6", "panda_link7", "panda_hand", "panda_leftfinger", "panda_rightfinger"]


def main() -> None:
    k = yaml.safe_load(SRC.read_text())["robot_cfg"]["kinematics"]
    sph = k["collision_spheres"]
    ign = {(a, b) for a, lst in k["self_collision_ignore"].items() for b in lst}
    ign |= {(b, a) for a, b in ign}
    buf = k.get("self_collision_buffer", {})
    rows, link_of = [], []
    for li, name in enumerate(LINKS):
        for s in sph[name]:
            rows.append((li, *[float(v) for v in s["center"]], float(s["radius"])))
            link_of.append(name)
    pairs = []
    for i in range(len(rows)):
        for j in range(i + 1, len(rows)):
            a, b = link_of[i], link_of[j]
            if a != b and (a, b) not in ign:
                pairs.append((i, j))
    lines = ["// Generated by riscv/tools/gen_spheres.py from cuRobo franka.yml. Do not edit.",
             "#pragma once", f"#define GC_NSPH {len(rows)}", f"#define GC_NPAIR {len(pairs)}",
             "static const int SPH_LINK[GC_NSPH] = {" + ",".join(str(r[0]) for r in rows) + "};",
             "static const float SPH_LOCAL[GC_NSPH][4] = {"]
    lines += ["  {%.6ff, %.6ff, %.6ff, %.6ff}," % r[1:] for r in rows]
    lines += ["};", "static const unsigned short PAIR_A[GC_NPAIR] = {" + ",".join(str(p[0]) for p in pairs) + "};",
              "static const unsigned short PAIR_B[GC_NPAIR] = {" + ",".join(str(p[1]) for p in pairs) + "};",
              "// ra + rb + cuRobo self_collision_buffer of both links, per checked pair",
              "static const float PAIR_R[GC_NPAIR] = {" + ",".join(
                  "%.6ff" % (rows[i][4] + buf.get(link_of[i], 0.0) + rows[j][4] + buf.get(link_of[j], 0.0))
                  for i, j in pairs) + "};", ""]
    OUT.write_text("\n".join(lines))
    print(len(rows), "spheres", len(pairs), "pairs ->", OUT)


if __name__ == "__main__":
    main()
